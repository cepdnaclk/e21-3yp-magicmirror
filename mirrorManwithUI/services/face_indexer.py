import os

from config.settings import BUCKET_NAME, COLLECTION_ID
from config.aws_config import get_rekognition_client, get_s3_client

# AWS ???????????
rekognition = get_rekognition_client()
s3 = get_s3_client()

def dynamic_indexing():
    try:
        rekognition.create_collection(CollectionId=COLLECTION_ID)
        print(f"? Collection '{COLLECTION_ID}' ??????? ??????.")
    except rekognition.exceptions.ResourceAlreadyExistsException:
        print(f"?? Collection '{COLLECTION_ID}' ??????? ???????.")

    print(f"?? S3 Bucket ?? ??????? ??????: {BUCKET_NAME}")

    # ??????? ??? path ?? ???????? ??? ?????
    PREFIX = "public/face_entries/"
    response = s3.list_objects_v2(Bucket=BUCKET_NAME, Prefix=PREFIX)

    if 'Contents' not in response:
        print(f"? ???? ??? {PREFIX} ???????? ?????? ?????????? ???.")
        return

    for obj in response['Contents']:
        full_path = obj['Key'] # e.g., public/face_entries/thenuka_front.jpg

        # Folder ??? ??? filter ???? file ???? ???? ??????
        if full_path == PREFIX:
            continue

        if full_path.lower().endswith(('.jpg', '.jpeg', '.png')):

            # 1. ???????? ?? ????? ???? ?? ???? (thenuka_front.jpg)
            file_name_only = full_path.replace(PREFIX, "")

            # 2. '_front.jpg' ???? ????? ?? ???????? ID ?? ????
            if '_' in file_name_only:
                person_id = file_name_only.rsplit('_', 1)[0]

                # AWS ???? ???? / ????? ????? ?? ???????? ID ???? ???
                person_id = person_id.replace('/', '_')

                print(f"?? Indexing: {file_name_only} (ID: {person_id})")

                try:
                    # ?????? Bucket ?? ?? ???? Path (full_path) ??? ??? ??? ??????
                    rekognition.index_faces(
                        CollectionId=COLLECTION_ID,
                        Image={'S3Object': {'Bucket': BUCKET_NAME, 'Name': full_path}},
                        ExternalImageId=person_id,
                        DetectionAttributes=['ALL']
                    )
                    print(f"  ? ????????!")
                except Exception as e:
                    print(f"  ? ??????: {e}")

if __name__ == "__main__":
    dynamic_indexing()
